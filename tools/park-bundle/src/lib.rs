//! park-bundle: glues park-core into the ONE file (`park.rs`) that the game mod needs.
//!
//! Why: Horizon's mixin tool can only paste a single self-contained file into the game,
//! but park-core is many files. This tool follows the `mod name;` lines from park-core's
//! `lib.rs` (the way Rust itself does), pastes every file in place as `mod name { ... }`,
//! and fixes the few things the game would reject.
//!
//! What it does to the text, line by line (decisions D34 and the M0 plan):
//!   * `mod name;` becomes `mod name {`, then the file's lines, then `}`. `pub` and the
//!     attributes written above the line (like `#[cfg(test)]`) are kept.
//!   * `crate::` becomes `crate::game::htp_park::`, because in the game our code sits at
//!     that path. `my_crate::` and `$crate::` are left alone.
//!   * `//!` comments become `//` (the mixin tool refuses `//!`, it counts them as file attributes).
//!   * Items the game cannot take are refused with the file and line (see `find_refusal`).
//!   * Windows and Linux line endings are treated the same; the output always uses Linux ones.
//!   * Test blocks are kept as they are: the game never compiles test-only code.
//!
//! The tool reads text, not Rust "grammar" (no `syn`, see D34). That is simple and short,
//! but a little naive: it cannot tell a string from code, so park-core must follow the
//! rules in ARCHITECTURE section 2 (for example, never write `crate::` inside a string).
//! The compile test in `tests/glued.rs` catches anything that slips through.
//!
//! Module bodies are pasted WITHOUT extra indentation on purpose: indenting would change the
//! contents of any multi-line string. The generated file is not meant to be pretty.

use std::fmt;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// Where park-core's source lives, relative to the repo root.
pub const SOURCE_DIR: &str = "crates/park-core/src";
/// Where the generated file goes, relative to the repo root.
pub const OUTPUT_FILE: &str = "mods/native/mixins/horizon-theme-park/park.rs";
/// What `crate::` turns into. `htp_park` must match the module name in `horizon-mixin.toml`.
pub const GAME_PREFIX: &str = "crate::game::htp_park::";

/// The first lines of the generated file. They are `//` comments (not `//!`) on purpose.
const HEADER: &str = "\
// GENERATED by tools/park-bundle from crates/park-core/src. DO NOT EDIT BY HAND.
// Change the park-core files instead, then run: cargo run -p park-bundle
// (Module bodies below are pasted without indentation on purpose.)

";

/// Everything that can go wrong while gluing.
#[derive(Debug)]
pub enum BundleError {
    /// A file could not be read.
    Io { path: PathBuf, error: io::Error },
    /// A line uses something the game's mixin tool cannot take.
    Refused {
        file: PathBuf,
        line: usize,
        item: &'static str,
        why: &'static str,
    },
    /// `mod name;` was written but neither `name.rs` nor `name/mod.rs` exists.
    MissingModule {
        file: PathBuf,
        line: usize,
        name: String,
        // Boxed so the error type stays small (clippy's `result_large_err`).
        looked_in: Box<[PathBuf; 2]>,
    },
    /// Both `name.rs` and `name/mod.rs` exist, so it is unclear which one is meant.
    AmbiguousModule {
        file: PathBuf,
        line: usize,
        name: String,
        found: Box<[PathBuf; 2]>,
    },
}

impl fmt::Display for BundleError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            BundleError::Io { path, error } => {
                write!(f, "{}: could not read the file: {error}", shown(path))
            }
            BundleError::Refused {
                file,
                line,
                item,
                why,
            } => write!(
                f,
                "{}:{line}: {item} is not allowed in park-core: {why}",
                shown(file)
            ),
            BundleError::MissingModule {
                file,
                line,
                name,
                looked_in,
            } => write!(
                f,
                "{}:{line}: `mod {name};` has no file. Looked for {} and {}",
                shown(file),
                shown(&looked_in[0]),
                shown(&looked_in[1])
            ),
            BundleError::AmbiguousModule {
                file,
                line,
                name,
                found,
            } => write!(
                f,
                "{}:{line}: `mod {name};` is ambiguous, both {} and {} exist. Keep only one",
                shown(file),
                shown(&found[0]),
                shown(&found[1])
            ),
        }
    }
}

impl std::error::Error for BundleError {}

/// A path as text with forward slashes, so messages look the same on every computer.
fn shown(path: &Path) -> String {
    path.display().to_string().replace('\\', "/")
}

/// Glue the crate whose source folder is `src_dir` (it must contain `lib.rs`) into one string.
pub fn bundle(src_dir: &Path) -> Result<String, BundleError> {
    let mut out = String::from(HEADER);
    paste_file(&src_dir.join("lib.rs"), src_dir, &mut out)?;
    Ok(out)
}

/// Append one file's lines to `out`, expanding its `mod name;` lines on the way.
///
/// `child_dir` is the folder where this file's child modules live: the crate's `src` folder for
/// `lib.rs`, and `<folder>/<name>` for both `<name>.rs` and `<name>/mod.rs` (Rust's own rule).
fn paste_file(file: &Path, child_dir: &Path, out: &mut String) -> Result<(), BundleError> {
    let text = fs::read_to_string(file).map_err(|error| BundleError::Io {
        path: file.to_path_buf(),
        error,
    })?;
    // Some Windows editors put an invisible marker (a "BOM") at the start of a file.
    let text = text.strip_prefix('\u{feff}').unwrap_or(&text);

    // `lines()` splits on both Windows (\r\n) and Linux (\n) endings, which is how
    // the two kinds of line ending end up treated alike.
    for (index, line) in text.lines().enumerate() {
        let line_number = index + 1;

        // Comment-only lines: never refused, never a `mod` line, but `//!` is rewritten
        // and `crate::` in them is fixed too (so doc links keep pointing at the right place).
        if is_comment_line(line) {
            out.push_str(&rewrite_crate_paths(&inner_doc_to_plain(line)));
            out.push('\n');
            continue;
        }

        if let Some(refusal) = find_refusal(line) {
            return Err(BundleError::Refused {
                file: file.to_path_buf(),
                line: line_number,
                item: refusal.item,
                why: refusal.why,
            });
        }

        match parse_mod_declaration(line) {
            Some(declaration) => {
                let (module_file, module_dir) =
                    find_module_file(file, line_number, declaration.name, child_dir)?;
                out.push_str(&format!(
                    "{}{}mod {} {{\n",
                    declaration.indent, declaration.visibility, declaration.name
                ));
                paste_file(&module_file, &module_dir, out)?;
                out.push_str(declaration.indent);
                out.push_str("}\n");
            }
            None => {
                out.push_str(&rewrite_crate_paths(line));
                out.push('\n');
            }
        }
    }
    Ok(())
}

/// True for a line that holds only a `//` comment (including `///` and `//!`).
fn is_comment_line(line: &str) -> bool {
    line.trim_start().starts_with("//")
}

/// Turn a leading `//!` into `//`, keeping the indentation. Other lines are unchanged.
fn inner_doc_to_plain(line: &str) -> String {
    let trimmed = line.trim_start();
    match trimmed.strip_prefix("//!") {
        Some(rest) => format!("{}//{rest}", &line[..line.len() - trimmed.len()]),
        None => line.to_string(),
    }
}

/// Letters, digits and `_`: the characters an identifier (a name in Rust) is made of.
fn is_ident_char(c: char) -> bool {
    c.is_alphanumeric() || c == '_'
}

/// Replace `crate::` with `GAME_PREFIX`, except in `my_crate::` and `$crate::`.
fn rewrite_crate_paths(line: &str) -> String {
    const NEEDLE: &str = "crate::";
    let mut out = String::with_capacity(line.len());
    let mut copied_up_to = 0;
    for (at, _) in line.match_indices(NEEDLE) {
        // Look at the character just before: a name character or `$` means it's a different word.
        let before = line[..at].chars().next_back();
        if before.is_some_and(|c| is_ident_char(c) || c == '$') {
            continue;
        }
        out.push_str(&line[copied_up_to..at]);
        out.push_str(GAME_PREFIX);
        copied_up_to = at + NEEDLE.len();
    }
    out.push_str(&line[copied_up_to..]);
    out
}

/// One thing the game cannot take, and why (shown to the person who wrote it).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Refusal {
    pub item: &'static str,
    pub why: &'static str,
}

// Attribute-like items. They are matched with all spaces removed, so `#[ path = "x" ]` is caught too.
const REFUSED_ATTRIBUTES: [(&str, Refusal); 3] = [
    (
        "#![",
        Refusal {
            item: "a file attribute `#![…]`",
            why: "the mixin tool refuses file attributes. Put crate-wide lint settings in park-core's Cargo.toml instead (`//!` comments are fine)",
        },
    ),
    (
        "#[path=",
        Refusal {
            item: "`#[path = …]`",
            why: "modules must be found by name: `mod x;` means x.rs or x/mod.rs",
        },
    ),
    (
        "#[macro_export",
        Refusal {
            item: "`#[macro_export]`",
            why: "an exported macro would leak out of our module into Horizon",
        },
    ),
];

// Macro calls. Matched only when the name starts a word, so `option_env!` is not mistaken for `env!`
// and a macro of your own called `my_env!` is fine.
const REFUSED_MACROS: [(&str, Refusal); 5] = [
    (
        "include!",
        Refusal {
            item: "`include!`",
            why: "the mixin tool refuses include macros; the glued file must be self-contained",
        },
    ),
    (
        "include_str!",
        Refusal {
            item: "`include_str!`",
            why: "the mixin tool refuses include macros; the glued file must be self-contained",
        },
    ),
    (
        "include_bytes!",
        Refusal {
            item: "`include_bytes!`",
            why: "the mixin tool refuses include macros; the glued file must be self-contained",
        },
    ),
    (
        "env!",
        Refusal {
            item: "`env!`",
            why: "inside the game it would read Horizon's build values, not ours",
        },
    ),
    (
        "option_env!",
        Refusal {
            item: "`option_env!`",
            why: "inside the game it would read Horizon's build values, not ours",
        },
    ),
];

const REFUSED_EXTERN_CRATE: Refusal = Refusal {
    item: "`extern crate`",
    why: "park-core only uses what its Cargo.toml lists, and `extern crate` does not work in the glued module",
};

/// Does `line` use something the game's mixin tool cannot take? Comment-only lines never do.
pub fn find_refusal(line: &str) -> Option<Refusal> {
    if is_comment_line(line) {
        return None;
    }

    let squashed: String = line.chars().filter(|c| !c.is_whitespace()).collect();
    for (pattern, refusal) in REFUSED_ATTRIBUTES {
        if squashed.contains(pattern) {
            return Some(refusal);
        }
    }

    for (pattern, refusal) in REFUSED_MACROS {
        if contains_as_word(line, pattern) {
            return Some(refusal);
        }
    }

    // `extern crate`: the two words next to each other, however many spaces are between them.
    let words: Vec<&str> = line.split_whitespace().collect();
    if words
        .windows(2)
        .any(|pair| pair[0] == "extern" && pair[1] == "crate")
    {
        return Some(REFUSED_EXTERN_CRATE);
    }
    None
}

/// Does `text` contain `pattern` with a non-name character (or nothing) just before it?
fn contains_as_word(text: &str, pattern: &str) -> bool {
    text.match_indices(pattern).any(|(at, _)| {
        text[..at]
            .chars()
            .next_back()
            .is_none_or(|before| !is_ident_char(before))
    })
}

/// A parsed `mod name;` line.
struct ModDeclaration<'a> {
    /// The spaces before it.
    indent: &'a str,
    /// `""`, `"pub "`, `"pub(crate) "` and so on, spaces included.
    visibility: &'a str,
    name: &'a str,
}

/// Recognise `mod name;` / `pub mod name;` written on one line (rule 9). Anything else is `None`.
fn parse_mod_declaration(line: &str) -> Option<ModDeclaration<'_>> {
    let trimmed = line.trim_start();
    let indent = &line[..line.len() - trimmed.len()];
    let (visibility, rest) = split_visibility(trimmed);

    let rest = rest.strip_prefix("mod")?;
    let after_mod = rest.trim_start();
    if after_mod.len() == rest.len() {
        return None; // something like `modx`, not the word `mod`
    }

    let name_end = after_mod
        .find(|c: char| !is_ident_char(c))
        .unwrap_or(after_mod.len());
    let name = &after_mod[..name_end];
    if name.is_empty() {
        return None;
    }

    // After the name there must be `;` and then nothing (or only a comment).
    let tail = after_mod[name_end..].trim_start().strip_prefix(';')?;
    let tail = tail.trim_start();
    if !(tail.is_empty() || tail.starts_with("//")) {
        return None;
    }
    Some(ModDeclaration {
        indent,
        visibility,
        name,
    })
}

/// Split `pub(crate) mod x;` into (`pub(crate) `, `mod x;`). With no `pub`, the first part is empty.
fn split_visibility(text: &str) -> (&str, &str) {
    let Some(after_pub) = text.strip_prefix("pub") else {
        return ("", text);
    };
    let after_vis = if after_pub.starts_with('(') {
        match after_pub.find(')') {
            Some(close) => &after_pub[close + 1..],
            None => return ("", text),
        }
    } else {
        after_pub
    };
    let rest = after_vis.trim_start();
    if rest.len() == after_vis.len() {
        return ("", text); // no space after `pub`, so it is some other word
    }
    (&text[..text.len() - rest.len()], rest)
}

/// Find the file for `mod name;` and the folder where its own child modules live.
///
/// Only the file's own folder is searched, as Rust does. A `mod x;` inside an inline `mod y { }`
/// would really live in `y/`; this tool does not follow that, so it fails with "no file" (loudly,
/// not silently) instead.
fn find_module_file(
    parent_file: &Path,
    line: usize,
    name: &str,
    child_dir: &Path,
) -> Result<(PathBuf, PathBuf), BundleError> {
    let flat = child_dir.join(format!("{name}.rs"));
    let nested = child_dir.join(name).join("mod.rs");
    let own_dir = child_dir.join(name);
    match (flat.is_file(), nested.is_file()) {
        (true, false) => Ok((flat, own_dir)),
        (false, true) => Ok((nested, own_dir)),
        (true, true) => Err(BundleError::AmbiguousModule {
            file: parent_file.to_path_buf(),
            line,
            name: name.to_string(),
            found: Box::new([flat, nested]),
        }),
        (false, false) => Err(BundleError::MissingModule {
            file: parent_file.to_path_buf(),
            line,
            name: name.to_string(),
            looked_in: Box::new([flat, nested]),
        }),
    }
}

/// What a run of the tool ends with: an exit code and a message to print.
///
/// Codes: 0 = all good, 1 = `--check` found `park.rs` stale, 2 = something is wrong (bad
/// arguments, a refused item, a missing file).
#[derive(Debug)]
pub struct Outcome {
    pub code: i32,
    pub message: String,
}

/// Run the tool for the repo at `root`. `args` are the command-line words after the program name.
pub fn run(args: &[String], root: &Path) -> Outcome {
    let check_only = match args {
        [] => false,
        [flag] if flag == "--check" => true,
        _ => {
            return Outcome {
                code: 2,
                message: "usage: park-bundle [--check]".to_string(),
            };
        }
    };

    let output_path = root.join(OUTPUT_FILE);
    let fresh = match bundle(&root.join(SOURCE_DIR)) {
        Ok(text) => text,
        Err(error) => {
            // Show repo-relative paths in messages.
            let root_prefix = format!("{}/", shown(root));
            return Outcome {
                code: 2,
                message: error.to_string().replace(&root_prefix, ""),
            };
        }
    };

    if check_only {
        check(&fresh, &output_path)
    } else {
        write(&fresh, &output_path)
    }
}

/// `--check`: is the file on disk the same as a fresh glue? Line-ending style does not matter.
fn check(fresh: &str, output_path: &Path) -> Outcome {
    let stale = Outcome {
        code: 1,
        message: format!("park.rs is stale, run `cargo run -p park-bundle` (file: {OUTPUT_FILE})"),
    };
    match fs::read_to_string(output_path) {
        Ok(on_disk) if same_ignoring_line_endings(&on_disk, fresh) => Outcome {
            code: 0,
            message: "park.rs is up to date".to_string(),
        },
        // Different, or missing: either way it needs re-gluing.
        _ => stale,
    }
}

/// Normal mode: write the glued file.
fn write(fresh: &str, output_path: &Path) -> Outcome {
    let result = output_path
        .parent()
        .map_or(Ok(()), fs::create_dir_all)
        .and_then(|()| fs::write(output_path, fresh));
    match result {
        Ok(()) => Outcome {
            code: 0,
            message: format!("wrote {OUTPUT_FILE} ({} lines)", fresh.lines().count()),
        },
        Err(error) => Outcome {
            code: 2,
            message: format!("{}: could not write: {error}", shown(output_path)),
        },
    }
}

fn same_ignoring_line_endings(a: &str, b: &str) -> bool {
    a.replace("\r\n", "\n") == b.replace("\r\n", "\n")
}
